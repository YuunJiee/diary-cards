export type Locale = "zh-TW" | "zh-CN" | "en";

/** 目前的介面文字；setLocale 會換掉裡面的內容，所以其他檔案可以直接 import 使用 */
export const t: Strings = { ...zh };
export let locale: Locale = "zh-TW";

const DICTS: Record<Locale, Strings> = { "zh-TW": zh, "zh-CN": zhCN, en };

export function setLocale(l: Locale) {
	locale = l;
	Object.assign(t, DICTS[l]);
}

/** Obsidian 的介面語言（存在 localStorage，英文時沒有值） */
export function obsidianLocale(): Locale {
	let lang: string | null = null;
	try {
		lang = window.localStorage.getItem("language");
	} catch {
		// 讀不到就當英文
	}
	// Obsidian 的語言代碼：zh 是簡體、zh-TW 是繁體
	const l = lang?.toLowerCase() ?? "";
	if (l === "zh-tw" || l === "zh-hk" || l === "zh-hant") return "zh-TW";
	if (l.startsWith("zh")) return "zh-CN";
	return "en";
}
